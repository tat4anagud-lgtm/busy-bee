/* ========================================
   BUSY BEE — СТРАНИЦЫ-ЗАГЛУШКИ (логика)
   ========================================
   Пара к errors-style.css. Пока всего одна вещь: кнопка «Обновить
   страницу» — перезагружает страницу через location.reload().
   Нужна там, где проблема может исчезнуть сама (нет соединения,
   сервер прилёг отдохнуть) — в отличие от 404 или 403, где
   обновление ничего не изменит и такой кнопки нет.

   Подключать после script.js, перед footer.js — как на 404.html. */

document.addEventListener("DOMContentLoaded", () => {

    document.querySelectorAll("[data-retry]").forEach((btn) => {
        btn.addEventListener("click", () => location.reload());
    });

});
